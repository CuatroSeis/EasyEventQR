export type Idioma = 'es' | 'en'

const CLAVE = 'easyeventqr-idioma'

/** Auto del navegador; cualquier cosa que no sea inglés = español. */
export function detectarIdioma(navigatorLanguage?: string): Idioma {
  const l = (navigatorLanguage ?? '').toLowerCase()
  return l.startsWith('en') ? 'en' : 'es'
}

export function leerIdioma(): Idioma {
  try {
    const g = (globalThis as any)?.localStorage?.getItem?.(CLAVE) ?? null
    if (g === 'es' || g === 'en') return g
    const nav = (globalThis as any)?.navigator?.language as string | undefined
    return detectarIdioma(nav)
  } catch {
    return 'es'
  }
}

export function guardarIdioma(idioma: Idioma): void {
  try {
    ;(globalThis as any)?.localStorage?.setItem?.(CLAVE, idioma)
  } catch {
    // Modo privado: queda en memoria de la sesión.
  }
}

