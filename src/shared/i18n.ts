export type ClaveTexto = keyof typeof STRINGS

/** `t('home.buscar.boton')` o `t('saludo', { nombre })` con `{nombre}` en el texto. */
export function traducir(idioma: Idioma, clave: ClaveTexto, vars?: Record<string, string | number>): string {
  let texto: string = STRINGS[clave][idioma]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) texto = texto.replaceAll(`{${k}}`, String(v))
  }
  return texto
}
